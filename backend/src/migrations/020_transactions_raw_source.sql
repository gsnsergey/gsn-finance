-- Сырые исходные данные строки выписки (rawSource).
--
-- Зачем:
--   Парсеры сохраняют оригинальную строку CSV / блок текста PDF в
--   preview.rawSource, и до импорта её можно посмотреть в превью. После
--   записи операции эти данные терялись: в форме операции нельзя было
--   проверить, что именно пришло из файла банка. Храним строку в
--   transactions.rawSource и показываем её в форме операции сворачиваемым
--   блоком «Исходные данные из выписки».
--
--   Для ручных операций (source != 'import') колонка остаётся NULL — там
--   исходной строки выписки нет по определению; форма просто не показывает
--   блок. Для перевода обе ноги получают одинаковый rawSource (склейку двух
--   строк файла).

ALTER TABLE transactions ADD COLUMN rawSource TEXT;
