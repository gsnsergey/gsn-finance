-- accounts.accountNumber: номер банковского счёта (20 цифр для РФ).
--
-- Зачем:
--   1. Автоматический резолв счёта при импорте выписок Точка-Банка.
--      CSV Точки содержит колонки «Счёт плательщика» и «Счёт получателя»
--      — по ним можно автоматически сопоставить операцию с accountId в БД.
--      Раньше приходилось выбирать руками для каждой операции.
--   2. Удобство: пользователь видит и редактирует номер счёта в карточке
--      счёта (как в банковском приложении).
--
-- Колонка NULLABLE: номер счёта опционален (для type='property' номера нет,
-- для счетов без чёткого номера тоже). Заполняется вручную через UI.
--
-- Поиск по (bank, accountNumber) — индекс, чтобы import-preview не делал
-- full scan по accounts на каждом импорте.
--
-- Не делаем UNIQUE: в теории один р/с может фигурировать в нескольких
-- строках (например, основной + резервный для одного и того же банка),
-- хотя на практике для Точка/Альфа/Сбер это 1:1.

ALTER TABLE accounts ADD COLUMN accountNumber TEXT;

CREATE INDEX idx_accounts_account_number ON accounts(bank, accountNumber);